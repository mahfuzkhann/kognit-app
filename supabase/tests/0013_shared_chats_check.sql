-- ---- helpers ---------------------------------------------------------------
create or replace function pg_temp.expect_error(stmt text, needle text) returns void language plpgsql as $$
begin
  begin
    execute stmt;
  exception when others then
    if sqlerrm ilike '%' || needle || '%' or sqlstate = needle then return; end if;
    raise exception 'EXPECTED error containing %, got [%] %', needle, sqlstate, sqlerrm;
  end;
  raise exception 'EXPECTED an error containing "%" but the statement succeeded: %', needle, stmt;
end $$;
grant execute on function pg_temp.expect_error(text, text) to public;

-- ---- 1. owner can create; the database makes the token; client input is ignored
set role authenticated;
select set_config('request.jwt.claim.sub', 'aaaaaaaa-0000-0000-0000-000000000001', false);

