-- ---- 5. anonymous visitor: only the function, nothing else -------------------
create temp table _tok as select share_token as t from public.shared_chats where chat_ref = 'chat_1';
grant select on _tok to anon;
reset role; set role anon;
select set_config('request.jwt.claim.sub', '', false);
select pg_temp.expect_error($q$select * from public.shared_chats$q$, 'permission denied');
select pg_temp.expect_error($q$insert into public.shared_chats (user_id,chat_ref,share_token,title,snapshot,message_count) values ('aaaaaaaa-0000-0000-0000-000000000001','anon','x','t','[{"role":"user","text":"x"}]',1)$q$, 'permission denied');
select pg_temp.expect_error($q$delete from public.shared_chats$q$, 'permission denied');
do $$ declare r jsonb; tok text; begin
  select t into tok from _tok;
  r := public.get_shared_chat(tok);
  if r is null then raise exception 'FAIL: the live token returned nothing'; end if;
  if (select array_agg(k order by k) from jsonb_object_keys(r) k) is distinct from array['created_at','message_count','snapshot','title'] then
    raise exception 'FAIL: unexpected keys %', r; end if;
  if r::text ilike '%aaaaaaaa%' or r::text ilike '%chat_1%' or r::text like '%' || tok || '%' then raise exception 'FAIL: owner data leaked: %', r; end if;
  if public.get_shared_chat(repeat('0', 40)) is not null then raise exception 'FAIL: unknown token returned data'; end if;
  if public.get_shared_chat('short') is not null or public.get_shared_chat('') is not null or public.get_shared_chat(null) is not null then raise exception 'FAIL: malformed token returned data'; end if;
  if public.get_shared_chat(upper(tok)) is not null then raise exception 'FAIL: token matched case-insensitively'; end if;
  if public.get_shared_chat(tok || ' OR 1=1') is not null or public.get_shared_chat('x'' or ''1''=''1') is not null then raise exception 'FAIL: injection-shaped input matched'; end if;
  raise notice 'ok 5: anon can only call get_shared_chat(); it returns exactly 4 keys and no owner data; bad tokens return null';
end $$;

-- ---- 6. revocation: delete -> link dead, content gone -------------------------
